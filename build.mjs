// Builds dist/code.js (Figma main thread) and dist/ui.html (single file, with the LittleCMS WASM inlined).
import { build, context } from 'esbuild';
import fs from 'fs';
import { generateNotices } from './scripts/notices.mjs';
const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const watch = process.argv.includes('--watch');

// Traditional Chinese is generated from the Simplified source with OpenCC (Taiwan phrasing)
{
  const tmp = 'node_modules/.cache/presskit-dict.mjs';
  fs.mkdirSync('node_modules/.cache', { recursive: true });
  await build({ entryPoints: ['src/i18n/dict.ts'], outfile: tmp, format: 'esm', bundle: true, logLevel: 'warning' });
  const { DICT } = await import('./' + tmp + '?t=' + Date.now());
  const OpenCC = (await import('opencc-js')).default;
  const conv = OpenCC.Converter({ from: 'cn', to: 'twp' });
  const map = {};
  for (const row of DICT) map[row[0]] = conv(row[0]);
  fs.writeFileSync('src/i18n/zh-tw.generated.ts', '// generated by build.mjs from dict.ts — do not edit\nexport const ZH_TW: Record<string, string> = ' + JSON.stringify(map, null, 0) + ';\n');
  console.log(`zh-TW: ${Object.keys(map).length} strings`);
}
fs.mkdirSync('dist', { recursive: true });
const wasmB64 = fs.readFileSync('node_modules/lcms-wasm/dist/lcms.wasm').toString('base64');

const inlineUi = {
  name: 'inline-ui',
  setup(b) {
    b.onEnd((r) => {
      if (r.errors.length) return;
      const notices = generateNotices(r.metafile);
      const js = fs.readFileSync('dist/ui.js', 'utf8').replace(/<\/script/gi, '<\\/script');
      const css = fs.readFileSync('dist/ui.css', 'utf8').replace(/<\/style/gi, '<\\/style');
      const html = fs.readFileSync('src/ui/ui.html', 'utf8').replace('/*__UI_CSS__*/', () => css).replace('/*__UI_JS__*/', () => js).replace('__THIRD_PARTY_NOTICES__', () => escapeHtml(notices));
      fs.writeFileSync('dist/ui.html', html);
      fs.rmSync('dist/ui.js');
      fs.rmSync('dist/ui.css');
      console.log(`ui.html ${(html.length / 1024).toFixed(0)} KB`);
    });
  },
};

const main = { entryPoints: ['src/main/code.ts'], outfile: 'dist/code.js', bundle: true, target: 'es2017', format: 'iife', logLevel: 'info' };
const ui = {
  entryPoints: ['src/ui/app.tsx'],
  outfile: 'dist/ui.js',
  bundle: true,
  target: 'es2020',
  format: 'iife',
  minify: !watch,
  metafile: true,
  loader: { '.module.css': 'local-css' },
  define: { __LCMS_WASM_B64__: JSON.stringify(wasmB64), 'import.meta.url': '"file:///presskit/lcms.js"', 'process.env.NODE_ENV': '"production"' },
  // lcms-wasm's Emscripten loader probes for Node; keep those branches inert in the browser build
  external: ['module', 'fs', 'path', 'url'],
  plugins: [inlineUi],
  logLevel: 'info',
};

if (watch) {
  (await context(main)).watch();
  (await context(ui)).watch();
} else {
  await build(main);
  const result = await build(ui);
  fs.writeFileSync('dist/ui-metafile.json', JSON.stringify(result.metafile, null, 2));
}
